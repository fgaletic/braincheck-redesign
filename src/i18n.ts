export const dictionaries: Record<Lang, Record<Key, string>> = { en, es };

export type TFn = (key: Key, params?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  const template = dictionaries[lang][key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in params ? String(params[name]) : `{${name}}`));
}

export function makeT(lang: Lang): TFn {
  return (key, params) => translate(lang, key, params);
}

/** Spanish device locales default to Spanish, everything else to English. */
export function detectLang(): Lang {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase().startsWith('es') ? 'es' : 'en';
  } catch {
    return 'en';
  }
}
